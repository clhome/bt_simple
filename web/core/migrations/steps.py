"""
结构对齐（schema.py）能自愈「缺表 / 缺列」，但**改不了已有数据**。
凡是需要搬运/清洗数据的变更，都在这里登记成一个步骤。

约定（runner 依赖这些约定，改动前请先读懂）：

  1. `STEPS` 必须按版本号升序，且**版本号一经发布不得复用**。
  2. 每个步骤函数签名固定为 `fn(conn) -> None`，`conn` 是 sqlite3 连接。
     抛异常 = 本次迁移失败 -> 事件回滚 -> 不记录版本 -> 下次启动自动重试（自愈）。
  3. 步骤必须**幂等**。理由：用户可能从旧备份恢复数据库，那时版本表比代码落后，
     步骤会被重放；如果步骤不幂等，重放就会把数据搞坏。
     推荐写法：先判断目标状态是否已达成，再决定要不要动。
  4. 不要在步骤里调用 `core.yf.writeLog` 之类的面板 DB 写接口 —— 迁移期间 schema
     正在变动，且会引入循环依赖。用 runner 传入的 `log` 或直接 print。
"""

import logging

log = logging.getLogger('yf.migrations')


def _step_noop(conn):
    """基线占位：结构对齐由 runner 负责，这里不需要动数据。"""


# [(版本号, 名称, 函数), ...]
STEPS = [
    (1, 'baseline', _step_noop),
]

LATEST_VERSION = max(seq for seq, _name, _fn in STEPS)
